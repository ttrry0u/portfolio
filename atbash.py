def atbash_cipher(text):
    # Русский алфавит из 32 букв (без буквы «ё»). Длина алфавита = 32, индексы от 0 до 31.
    alphabet = 'абвгдежзийклмнопрстуфхцчшщъыьэюя'

    # Словарь замены знаков препинания на кодовые слова (для шифрования).
    # Каждый знак препинания заменяется на последовательность букв,
    # чтобы текст после шифрования состоял только из букв алфавита.
    punct_dict = {
        '.': 'тчк',
        ',': 'зпт',
        '?': 'впр',
        '!': 'вск',
        '"': 'квч',
        '-': 'тире',
        '(': 'скоб',
        ')': 'скобз',
        "'": 'апстр'
    }

    # Обратный словарь для восстановления знаков препинания (при расшифровании).
    reverse_punct_dict = {v: k for k, v in punct_dict.items()}

    # Приведение текста к нижнему регистру и замена букв «ё» на «е».
    # Это необходимо, потому что алфавит не содержит «ё».
    text = text.lower()
    text = text.replace('ё', 'е')

    if ' ' in text:
        # ------------------- РЕЖИМ ШИФРОВАНИЯ -------------------
        # Если в тексте есть пробел, считаем, что это исходный открытый текст.
        # Заменяем все знаки препинания на соответствующие кодовые слова.
        for punct, replacement in punct_dict.items():
            text = text.replace(punct, replacement)

        # Пробел заменяем на специальное слово 'прбл' (сокращение от «пробел»).
        text = text.replace(' ', 'прбл')

        # Основной цикл шифрования: для каждого символа обработанного текста
        # находим его индекс в алфавите и заменяем буквой с «противоположным» индексом.
        result = []
        for i in text:                               # i — текущий символ (например, 'а', 'б', …)
            if i in alphabet:
                index = alphabet.index(i)             # номер буквы в алфавите (0…31)
                # Формула шифра Атбаш: буква с индексом k заменяется буквой с индексом (31 - k).
                result.append(alphabet[31 - index])
            else:
                # Если символ не принадлежит алфавиту (например, цифра), оставляем без изменений.
                result.append(i)

        # Возвращаем зашифрованную строку (без пробелов, знаки заменены на коды).
        return ''.join(result)
    else:
        # ------------------- РЕЖИМ РАСШИФРОВАНИЯ -------------------
        # Если в тексте нет пробелов, предполагаем, что это шифртекст.
        # Расшифрование Атбаш идентично шифрованию (обратная замена букв).
        decrypted_chars = []
        for i in text:
            if i in alphabet:
                index = alphabet.index(i)
                decrypted_chars.append(alphabet[31 - index])   # та же формула
            else:
                decrypted_chars.append(i)

        decrypted_text = ''.join(decrypted_chars)

        # Восстанавливаем пробелы: заменяем 'прбл' обратно на пробел.
        decrypted_text = decrypted_text.replace('прбл', ' ')

        # Восстанавливаем знаки препинания: заменяем кодовые слова на соответствующие символы.
        for word, punct in reverse_punct_dict.items():
            decrypted_text = decrypted_text.replace(word, punct)

        return decrypted_text


