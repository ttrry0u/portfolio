    # Пример работы шифра Атбаш
    test_text = "волк каждый год линяет, а все сер бывает."
    print("=" * 50)
    print("Исходный текст:", test_text)
    print("=" * 50)

    # Шифрование тестового текста
    encrypted = atbash_cipher(test_text)
    print("Зашифрованный текст:", encrypted)

    # Расшифрование обратно (обратимая операция)
    decrypted = atbash_cipher(encrypted)
    print("Расшифрованный текст:", decrypted)

    # Проверка, что расшифрованный текст совпадает с исходным
    print("Совпадает с исходным:", test_text.lower().replace('ё', 'е') == decrypted)

