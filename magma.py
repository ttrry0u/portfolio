def magma_transform(input_hex):
    #s-блоки (8 штук, каждый содержит 16 значений от 0 до 15)
    sboxes = [
        [12, 4, 6, 2, 10, 5, 11, 9, 14, 8, 13, 7, 0, 3, 15, 1],
        [6, 8, 2, 3, 9, 10, 5, 12, 1, 14, 4, 7, 11, 13, 0, 15],
        [11, 3, 5, 8, 2, 15, 10, 13, 14, 1, 7, 4, 12, 9, 6, 0],
        [12, 8, 2, 1, 13, 4, 15, 6, 7, 0, 10, 5, 3, 14, 9, 11],
        [7, 15, 5, 10, 8, 1, 6, 13, 0, 9, 3, 14, 11, 4, 2, 12],
        [5, 13, 15, 6, 9, 2, 12, 10, 11, 7, 8, 1, 4, 3, 14, 0],
        [8, 14, 2, 5, 6, 9, 1, 12, 15, 4, 11, 0, 13, 10, 3, 7],
        [1, 7, 14, 13, 0, 5, 8, 3, 4, 15, 10, 6, 9, 12, 11, 2]
    ]

    #приводим введённую строку к нижнему регистру для проверки
    input_hex = input_hex.lower()

    #проверка: длина ровно 8 символов и все символы шестнадцатеричные
    if len(input_hex) != 8 or not all(c in '0123456789abcdef' for c in input_hex):
        return "Ошибка: введите 8 шестнадцатеричных символов (0-9, a-f)"

    #преобразуем шестнадцатеричную строку в целое число
    value = int(input_hex, 16)

    #извлекаем из числа 8 полубайт (по 4 бита)
    #начинаем с младшего полубайта (i=0)
    nibbles = []
    for i in range(8):
        #сдвигаем вправо на 4*i бит и берём младшие 4 бита
        nibble = (value >> (4 * i)) & 0xF
        nibbles.append(nibble)

    #применяем S-блоки: для каждого i-го полубайта используем i-й S-блок
    result = 0
    for i in range(8):
        #заменяем значение по таблице замен
        substituted = sboxes[i][nibbles[i]]
        #записываем результат на ту же позицию (i-й полубайт)
        result |= (substituted << (4 * i))

    #преобразуем полученное число обратно в 8-символьную шестнадцатеричную строку
    return format(result, '08x').upper()


